-- V1: Esquema inicial de la base de datos
-- Define las tablas principales antes de las migraciones incrementales.

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255),
    email VARCHAR(255),
    password VARCHAR(255),
    role VARCHAR(20)
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    category VARCHAR(255),
    price NUMERIC(38, 2),
    stock INTEGER,
    active BOOLEAN
);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT,
    product_name VARCHAR(255),
    quantity INTEGER,
    unit_price NUMERIC(38, 2),
    total NUMERIC(38, 2),
    customer_name VARCHAR(255),
    sold_at TIMESTAMP
);

CREATE TABLE customer_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    created_at TIMESTAMP,
    total NUMERIC(38, 2),
    CONSTRAINT fk_customer_orders_customer
        FOREIGN KEY (customer_id) REFERENCES users(id)
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT,
    product_name VARCHAR(255),
    quantity INTEGER,
    unit_price NUMERIC(38, 2),
    line_total NUMERIC(38, 2),
    CONSTRAINT fk_order_items_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(id)
);

CREATE TABLE customer_claims (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    reason VARCHAR(80) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    status VARCHAR(20) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_customer_claims_order
        FOREIGN KEY (order_id) REFERENCES customer_orders(id),
    CONSTRAINT fk_customer_claims_order_item
        FOREIGN KEY (order_item_id) REFERENCES order_items(id)
);
