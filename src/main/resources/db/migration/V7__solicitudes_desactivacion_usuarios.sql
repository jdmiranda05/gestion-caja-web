-- V7: Solicitudes de desactivacion de usuarios.

CREATE TABLE user_deactivation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_user_id BIGINT NOT NULL,
    requested_by_user_id BIGINT NOT NULL,
    approved_by_user_id BIGINT,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    reason VARCHAR(1000) NOT NULL,
    requested_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    decided_at TIMESTAMP,
    executed_at TIMESTAMP,

    CONSTRAINT fk_deactivation_target
        FOREIGN KEY (target_user_id) REFERENCES users(id),

    CONSTRAINT fk_deactivation_requester
        FOREIGN KEY (requested_by_user_id) REFERENCES users(id),

    CONSTRAINT fk_deactivation_approver
        FOREIGN KEY (approved_by_user_id) REFERENCES users(id),

    CONSTRAINT chk_deactivation_status
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'EXECUTED'))
);

-- Historial de acciones administrativas.

CREATE TABLE user_admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id BIGINT NOT NULL,
    actor_user_id BIGINT NOT NULL,
    action VARCHAR(40) NOT NULL,
    details VARCHAR(2000),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_user_audit_request
        FOREIGN KEY (request_id)
        REFERENCES user_deactivation_requests(id),

    CONSTRAINT fk_user_audit_actor
        FOREIGN KEY (actor_user_id)
        REFERENCES users(id)
);

CREATE INDEX idx_deactivation_target
    ON user_deactivation_requests(target_user_id);

CREATE INDEX idx_deactivation_status
    ON user_deactivation_requests(status);

CREATE INDEX idx_user_audit_request
    ON user_admin_audit(request_id);